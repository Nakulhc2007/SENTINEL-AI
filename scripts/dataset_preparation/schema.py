"""
SENTINEL-AI — Common Event Schema (CES)
========================================
All datasets (real and synthetic) are normalized into this unified schema
before being written to data/processed/normalized/.

Record types:
  - "real"      : derived from a real-world public dataset
  - "synthetic" : generated by the SENTINEL-AI synthetic generator

Schema version: 1.0.0
"""

import uuid
import hashlib
from datetime import datetime, timezone
from typing import Optional, Any

# ── Severity levels ──────────────────────────────────────────────────────────
SEVERITY_INFO     = 0
SEVERITY_LOW      = 1
SEVERITY_MEDIUM   = 2
SEVERITY_HIGH     = 3
SEVERITY_CRITICAL = 4

SEVERITY_LABELS = {
    0: "info",
    1: "low",
    2: "medium",
    3: "high",
    4: "critical",
}

# ── Supported domains ─────────────────────────────────────────────────────────
DOMAINS = [
    "network_security",
    "endpoint_security",
    "cloud_infrastructure",
    "iam",
    "application_security",
    "dlp",
    "insider_threat",
    "compliance",
]

# ── Source dataset identifiers ────────────────────────────────────────────────
SOURCE_CICIDS2017    = "cicids2017"
SOURCE_LOGHUB_HDFS   = "loghub_hdfs"
SOURCE_LOGHUB_WIN    = "loghub_windows"
SOURCE_LOGHUB_LINUX  = "loghub_linux"
SOURCE_CERT_INSIDER  = "cert_insider_r62"

def synthetic_source(domain: str) -> str:
    return f"synthetic_{domain}"


def make_event_id() -> str:
    return str(uuid.uuid4())


def sha256_of(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8", errors="replace")).hexdigest()


def build_record(
    *,
    domain: str,
    source_dataset: str,
    record_type: str,           # "real" | "synthetic"
    timestamp: datetime,
    event_type: str,            # auth | network | process | file | web | usb | email | api | audit
    severity: int,              # 0-4
    action: str,
    raw_log: str,
    src_ip: Optional[str] = None,
    dst_ip: Optional[str] = None,
    src_port: Optional[int] = None,
    dst_port: Optional[int] = None,
    protocol: Optional[str] = None,
    username: Optional[str] = None,
    hostname: Optional[str] = None,
    process_name: Optional[str] = None,
    file_path: Optional[str] = None,
    is_attack: Optional[bool] = None,
    attack_type: Optional[str] = None,
    organization_id: Optional[str] = None,
    extra_fields: Optional[dict] = None,
) -> dict:
    """Return a fully-formed CES record dict."""
    assert domain in DOMAINS, f"Unknown domain: {domain}"
    assert record_type in ("real", "synthetic"), f"Invalid record_type: {record_type}"
    assert 0 <= severity <= 4, f"Severity {severity} out of range"

    ts_str = timestamp.isoformat() if isinstance(timestamp, datetime) else str(timestamp)

    record = {
        # ── Identity ──────────────────────────────────────────────────────
        "event_id":         make_event_id(),
        "schema_version":   "1.0.0",
        "record_type":      record_type,
        "source_dataset":   source_dataset,
        "organization_id":  organization_id or "",

        # ── Classification ────────────────────────────────────────────────
        "domain":           domain,
        "event_type":       event_type,
        "severity":         severity,
        "severity_label":   SEVERITY_LABELS[severity],

        # ── Timing ───────────────────────────────────────────────────────
        "timestamp":        ts_str,

        # ── Network fields ────────────────────────────────────────────────
        "src_ip":           src_ip,
        "dst_ip":           dst_ip,
        "src_port":         src_port,
        "dst_port":         dst_port,
        "protocol":         protocol,

        # ── Identity / Host fields ────────────────────────────────────────
        "username":         username,
        "hostname":         hostname,
        "process_name":     process_name,
        "file_path":        file_path,

        # ── Event semantics ───────────────────────────────────────────────
        "action":           action,

        # ── Ground truth (preserved from original dataset) ────────────────
        "is_attack":        is_attack,
        "attack_type":      attack_type,

        # ── Raw log (original line) ───────────────────────────────────────
        "raw_log":          raw_log,

        # ── Integrity ─────────────────────────────────────────────────────
        "sha256":           sha256_of(raw_log),

        # ── Domain-specific extra fields ──────────────────────────────────
        "extra_fields":     extra_fields or {},
    }
    return record


# ── Field names in output order (for CSV column headers) ──────────────────────
CES_COLUMNS = [
    "event_id", "schema_version", "record_type", "source_dataset", "organization_id",
    "domain", "event_type", "severity", "severity_label", "timestamp",
    "src_ip", "dst_ip", "src_port", "dst_port", "protocol",
    "username", "hostname", "process_name", "file_path",
    "action", "is_attack", "attack_type", "raw_log", "sha256",
    # extra_fields stored as JSON in the CSV
    "extra_fields",
]


def validate_record(record: dict) -> list[str]:
    """Return list of validation errors for a CES record. Empty = valid."""
    errors = []
    required = ["event_id", "record_type", "source_dataset", "domain",
                 "event_type", "severity", "timestamp", "action", "raw_log", "sha256"]
    for field in required:
        if field not in record or record[field] is None:
            errors.append(f"Missing required field: {field}")
    if record.get("domain") not in DOMAINS:
        errors.append(f"Invalid domain: {record.get('domain')}")
    if record.get("record_type") not in ("real", "synthetic"):
        errors.append(f"Invalid record_type: {record.get('record_type')}")
    sev = record.get("severity")
    if sev is not None and not (0 <= int(sev) <= 4):
        errors.append(f"Severity {sev} out of range 0-4")
    return errors
